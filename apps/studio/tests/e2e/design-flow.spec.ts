test('edits native JSON Flow, reviews a real voice sample, generates dialogue and exports the same playable project', async ({ page, request }, testInfo) => {
  test.setTimeout(120000)
  const failures: string[] = []
  page.on('pageerror', error => failures.push(error.message))
  await page.goto('/')
  await expect(page.getByTestId('flow-workspace')).toBeVisible()
  await page.locator('.flow-node-list button').filter({ has: page.locator('code', { hasText: /^speech$/u }) }).click()
  const editor = page.getByTestId('flow-node-editor')
  await editor.getByLabel('文案', { exact: true }).fill(editedText)
  await editor.getByLabel('布局坐标 X', { exact: true }).fill('140')
  await editor.getByLabel('布局坐标 Y', { exact: true }).fill('240')
  await editor.getByLabel('布局坐标 Y', { exact: true }).blur()
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  await expect(editor.getByLabel('布局坐标 Y', { exact: true })).toHaveValue('0')
  await page.getByRole('button', { name: '重做', exact: true }).click()
  await expect(editor.getByLabel('布局坐标 Y', { exact: true })).toHaveValue('240')
  await page.getByRole('button', { name: '保存 JSON', exact: true }).click()
  await expect.poll(async () => JSON.parse((await files(page))['adv/chapters/intro.chapter.json']!).nodes.find((node: any) => node.id === 'speech').dialogues[0].text).toBe(editedText)
  const nativeChapter = JSON.parse((await files(page))['adv/chapters/intro.chapter.json']!)
  expect(nativeChapter.nodes.find((node: any) => node.id === 'speech')).toMatchObject({ position: { x: 140, y: 240 }, dialogues: [{ lineId, actorNote: 'retain-line-proof' }] })
  expect(nativeChapter.notes).toEqual({ retained: 'author-layout-proof' })
  await page.screenshot({ path: testInfo.outputPath('studio-flow-normal.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: testInfo.outputPath('studio-flow-narrow.png'), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.setViewportSize({ width: 1280, height: 900 })
  const designer = await createVoice(page)
  await planPreview(page)
  // An equivalent durable refresh must preserve the reviewed request.
  await designer.getByRole('button', { name: '恢复服务端结果', exact: true }).first().click()
  await expect(page.getByRole('button', { name: '生成已审核预览', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: '生成已审核预览', exact: true }).click()
  const candidate = designer.locator('[data-preview-id]')
  await expect(candidate.getByRole('button', { name: '登记已审核样本', exact: true })).toBeVisible()
  await candidate.getByRole('button', { name: '校验并试听', exact: true }).click()
  await expect(designer.locator('audio')).toHaveAttribute('src', /^blob:/u)
  const rms = await designer.locator('audio').evaluate(async (audio: HTMLAudioElement) => {
    const context = new AudioContext()
    const buffer = await context.decodeAudioData(await fetch(audio.src).then(response => response.arrayBuffer()))
    const data = buffer.getChannelData(0)
    const result = Math.sqrt(data.reduce((sum, sample) => sum + sample * sample, 0) / data.length)
    await context.close()
    return result
  })
  expect(rms).toBeGreaterThan(0.1)
  expect((await snapshot(page)).ledger.lines[lineId]).toBeUndefined()
  await candidate.getByRole('button', { name: '登记已审核样本', exact: true }).click()
  const sample = designer.locator('[data-sample-id]')
  await expect(sample).toHaveCount(1)
  await sample.getByRole('button', { name: '选择已审核样本', exact: true }).click()
  await designer.getByLabel('显式替换当前 Profile 供应商绑定', { exact: true }).check()
  await sample.getByRole('button', { name: '将所选样本应用到 Profile', exact: true }).click()
  await expect.poll(async () => JSON.parse((await files(page))['adv/settings/game.json']!).characters[0].voiceProfile.locales['zh-CN'].providers['fixture-tts'].projectVoiceId).toBe('hero-design-v1')
  await page.screenshot({ path: testInfo.outputPath('studio-design-normal.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('studio-design-narrow.png'), fullPage: true })
  await page.evaluate(() => (window as any).designFlowFixture.locale('en'))
  await expect(designer.getByRole('heading', { name: 'Voice design', exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('studio-design-en-narrow.png'), fullPage: true })
  await page.evaluate(() => (window as any).designFlowFixture.locale('zh-CN'))
  await page.getByRole('button', { name: '生成配音', exact: true }).click()
  const jobs = page.getByTestId('voice-jobs')
  await jobs.getByRole('checkbox').check()
  await jobs.getByRole('button', { name: '审核生成计划', exact: true }).click()
  await expect(jobs.getByRole('button', { name: '确认并保存计划' })).toBeVisible()
  await jobs.getByRole('button', { name: '确认并保存计划' }).click()
  await jobs.getByRole('button', { name: '执行已确认计划', exact: true }).click()
  await expect.poll(async () => (await snapshot(page)).ledger.lines[lineId]?.locales['zh-CN']?.takes.length).toBe(1)
  const generated = (await snapshot(page)).ledger.lines[lineId]!.locales['zh-CN']!.takes[0]!
  expect(generated).toMatchObject({ spokenText: editedText, source: 'system', projectVoiceId: 'hero-design-v1', projectVoiceVersion: '1' })
  await page.getByRole('button', { name: '配音审核', exact: true }).click()
  await page.locator('.voice-review__line').filter({ has: page.locator('code', { hasText: lineId }) }).getByRole('button', { name: '绑定此 take', exact: true }).click()
  await expect.poll(async () => (await snapshot(page)).ledger.lines[lineId]!.locales['zh-CN']!.selectedTake).toBe(generated.id)
  await page.evaluate(() => (window as any).designFlowFixture.sync())
  await page.evaluate(() => (window as any).designFlowFixture.persist())
  const server = await request.get('/fixture/status').then(response => response.json())
  expect(server.calls.filter((call: any) => call.text === editedText)).toHaveLength(1)
  expect(server.snapshot.ledger.lines[lineId].locales['zh-CN'].selectedTake).toBe(generated.id)
  await page.reload()
  await expect(page.getByTestId('flow-workspace')).toBeVisible()
  await page.getByRole('button', { name: '实际播放器', exact: true }).click()
  await expect(page.getByText(editedText, { exact: true })).toBeVisible()
  // Click the reading area; the center can contain controls that stop propagation.
  // The first click completes typewriting and the second advances the dialogue.
  for (let index = 0; index < 2 && !await page.getByRole('button', { name: '走左侧', exact: true }).isVisible(); index++)
    await page.locator('.adv-dialog-box:visible').click({ position: { x: 20, y: 20 } })
  await expect(page.getByRole('button', { name: '走左侧', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '走左侧', exact: true }).click()
  await expect(page.getByText('进入左侧分支。', { exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('studio-player-narrow.png'), fullPage: true })
  const exported = await page.evaluate(() => (window as any).designFlowFixture.export())
  expect(exported.diagnostics.filter((issue: any) => issue.severity === 'error')).toEqual([])
  expect(exported.chapterIds).toEqual(['intro'])
  expect(exported.files.some((path: string) => path.includes('voice/samples/'))).toBe(true)
  expect(exported.files).toContain('authoring/rights/original.json')
  expect(JSON.stringify(exported.program)).not.toContain('projectVoiceId')
  await writeFile(testInfo.outputPath('handoff.json'), JSON.stringify({ ...exported, rms }, null, 2))
  expect(failures).toEqual([])
  const playerProof = await verifyStudioHandoffPlayer(page, testInfo, { playerUrl: exported.playerUrl, lineId, text: editedText, takeId: generated.id, assetId: generated.assetId })
  const proofPath = testInfo.outputPath('player-proof.json')
  await writeFile(proofPath, JSON.stringify({ schemaVersion: 1, root: exported.root, outDir: exported.build.outDir, check: exported.check, ...playerProof }, null, 2))
  await testInfo.attach('native-player-proof', { path: proofPath, contentType: 'application/json' })
})
test('restores uncertain preview cancellation without repeating an accepted supplier request', async ({ page, request }) => {
  await page.goto('/')
  const designer = await createVoice(page)
  await planPreview(page)
  await request.post('/fixture/hold')
  await designer.getByRole('button', { name: '生成已审核预览', exact: true }).click()
  await expect.poll(async () => (await request.get('/fixture/status').then(response => response.json())).calls.length).toBe(1)
  await designer.getByRole('button', { name: '取消预览', exact: true }).click()
  await expect(designer.getByText(/fixture-tts.*结果未知/u)).toBeVisible()
  await page.evaluate(() => (window as any).designFlowFixture.persist())
  await page.reload()
  await page.getByRole('button', { name: '音频工作区', exact: true }).click()
  await page.getByRole('button', { name: '音色设计', exact: true }).click()
  await designer.getByRole('combobox', { name: '角色 / 项目旁白', exact: true }).selectOption('hero')
  await expect(designer.getByText(/fixture-tts.*结果未知/u)).toBeVisible()
  expect((await request.get('/fixture/status').then(response => response.json())).calls).toHaveLength(1)
  expect((await snapshot(page)).ledger.lines[lineId]).toBeUndefined()
})
