import { writeFile } from 'node:fs/promises'
import { expect, test } from '@playwright/test'

test('starts at the real template, approves the director graph and repairs a six-role candidate journey', async ({ page }, info) => {
  test.setTimeout(120000)
  const errors: string[] = []
  const warnings: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', (message) => {
    if (message.type() === 'error')
      errors.push(message.text())
    if (message.type() === 'warning')
      warnings.push(message.text())
  })
  const snapshot = () => page.evaluate(async () => {
    const fixture = (window as any).creativeAuthorFixture
    return { files: await fixture.files(), run: fixture.run(), calls: fixture.calls(), starts: fixture.startRequests(), handoffs: fixture.productionHandoffs(), repairs: fixture.repairHandoffs(), reports: fixture.playtests(), summaries: fixture.summaryHandoffs(), failures: fixture.fixtureFailures() }
  })
  const card = (summary: string) => page.locator('.team-artifact').filter({ has: page.getByRole('heading', { name: summary, exact: true }) }).last()
  async function select(summary: string) {
    await card(summary).getByRole('button', { name: '选定候选并继续', exact: true }).click()
  }
  try {
    await page.goto('/tests/fixtures/creative-team/authoring.html?case=production-start')
    await expect(page).toHaveTitle('Creative candidate UI fixture')
    await expect.poll(() => page.evaluate(() => Boolean((window as any).creativeAuthorFixture))).toBe(true)
    await expect(page.getByText('仅验证界面与创作协议，不作为六角色真实交付。')).toBeVisible()
    await expect(page.locator('vite-error-overlay')).toHaveCount(0)
    await expect(page.getByText('还没有制作组任务。可以先请导演制定计划，也可以直接找一位伙伴。')).toBeVisible()
    const initial = await snapshot()
    expect(Object.keys(initial.files).sort()).toEqual(['README.md', 'adv.config.json', 'adv/chapters/01.adv.md', 'adv/outline.md', 'adv/world.md'])
    expect(initial.calls.filter((call: string) => call.startsWith('POST'))).toEqual([])
    await page.locator('#team-goal').fill('  雨夜车站，两位主要人物，两个结局；缺失媒体如实交接。  ')
    await page.locator('#team-budget').fill('1.234')
    await page.getByRole('button', { name: '建立任务并审阅', exact: true }).click()
    await expect(page.getByRole('button', { name: '确认预算并开始', exact: true })).toBeVisible()
    const unapproved = await snapshot()
    expect(unapproved.starts).toHaveLength(1)
    expect(unapproved.starts[0].limits.maxMicroPoints).toBe(1234)
    expect(unapproved.starts[0].goal).toBe('雨夜车站，两位主要人物，两个结局；缺失媒体如实交接。')
    expect(unapproved.starts[0].project.files).toEqual(initial.files)
    expect(unapproved.run.status).toBe('awaiting_plan_review')
    expect(unapproved.handoffs).toEqual([])
    expect(unapproved.run.artifacts).toEqual([])
    expect(unapproved.files).toEqual(initial.files)
    await page.reload()
    await expect(page.getByRole('button', { name: '确认预算并开始', exact: true })).toBeVisible()
    expect((await snapshot()).calls.filter((call: string) => call.startsWith('POST'))).toEqual([])
    await page.getByRole('button', { name: '确认预算并开始', exact: true }).click()
    await expect(card('模板起步 · 六角色分工 fixture')).toBeVisible()
    expect((await snapshot()).run.plan.tasks).toHaveLength(1)
    await card('模板起步 · 六角色分工 fixture').getByText('查看完整内容', { exact: true }).click()
    for (const width of [1280, 390]) {
      await page.setViewportSize({ width, height: 900 })
      await card('模板起步 · 六角色分工 fixture').scrollIntoViewIfNeeded()
      await page.screenshot({ path: info.outputPath(`director-plan-${width}.png`), animations: 'disabled' })
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    }
    await card('模板起步 · 六角色分工 fixture').getByRole('button', { name: '确认分工并继续', exact: true }).click()
    await expect(card('模板起步 · 两位人物 fixture')).toBeVisible()
    expect((await snapshot()).run.plan.tasks).toHaveLength(7)
    await card('模板起步 · 两位人物 fixture').getByRole('button', { name: '编辑候选', exact: true }).click()
    const editor = page.locator('[data-testid="creative-candidate-editor"]:visible')
    await editor.locator('textarea[id$="-lin-motivation"]').fill('先核对信封署名，再寻找收件人')
    await editor.getByLabel('本次修改的原因').fill('让人物行动有明确依据')
    await editor.getByRole('button', { name: '保存候选修订', exact: true }).click()
    await select('模板起步 · 两位人物 fixture')
    await expect(card('模板起步 · 含预埋问题的章节 fixture')).toBeVisible()
    await card('模板起步 · 含预埋问题的章节 fixture').getByRole('button', { name: '编辑候选', exact: true }).click()
    const script = editor.getByRole('group', { name: '01', exact: true }).getByLabel('AdvScript', { exact: true })
    await expect(script).toHaveValue(/先核对信封署名，再寻找收件人/)
    await script.fill((await script.inputValue()).replace('等我确认信上的名字。', '让我再核对一次信上的名字。'))
    await editor.getByLabel('本次修改的原因').fill('作者改写一句对白并保留预埋悬空结局')
    await editor.getByRole('button', { name: '保存候选修订', exact: true }).click()
    await select('模板起步 · 含预埋问题的章节 fixture')
    await select('模板起步 · 美术交接 fixture')
    await select('模板起步 · 人物与旁白方案 fixture')
    await select('模板起步 · 两结局计划 fixture')
    const candidates = await snapshot()
    expect(new Set(candidates.run.artifacts.map((item: any) => item.partner))).toEqual(new Set(['director', 'character-designer', 'writer', 'art-director', 'voice-director', 'playtester']))
    expect(candidates.files).toEqual(initial.files)
    const playtest = page.getByTestId('creative-playtest')
    await playtest.getByRole('combobox', { name: '执行快照', exact: true }).selectOption('candidate')
    await playtest.getByRole('button', { name: '载入试玩员提出的路径', exact: true }).click()
    await playtest.getByRole('button', { name: '执行这些路径', exact: true }).click()
    await expect(playtest.getByText('已同步作者宿主报告，服务端未重放', { exact: true })).toBeVisible()
    const repair = page.getByTestId('creative-playtest-repair')
    await repair.getByRole('combobox', { name: '报告问题', exact: true }).selectOption({ label: 'ADV_RUNTIME_UNKNOWN_TARGET · adv/chapters/01.adv.md' })
    await repair.getByRole('combobox', { name: '负责任务', exact: true }).selectOption('script')
    await repair.getByRole('button', { name: '按此报告返工', exact: true }).click()
    await expect(card('模板起步 · 修复悬空结局 fixture')).toBeVisible()
    await select('模板起步 · 修复悬空结局 fixture')
    const repaired = await snapshot()
    expect(repaired.repairs).toHaveLength(1)
    expect(repaired.repairs[0].repair.finding.code).toBe('ADV_RUNTIME_UNKNOWN_TARGET')
    expect(repaired.run.artifacts.find((item: any) => item.taskId === 'art').status).toBe('selected')
    expect(repaired.run.tasks.find((item: any) => item.taskId === 'voice').status).toBe('stale')
    for (const [taskId, summary] of [['voice', '模板起步 · 人物与旁白方案 fixture'], ['check', '模板起步 · 两结局计划 fixture']]) {
      const rework = page.getByTestId('creative-task-rework').filter({ has: page.locator(`#creative-rework-${taskId}`) })
      await rework.locator('textarea').fill('作者明确要求按修复后的章节重新核对，保留独立美术候选')
      await rework.getByRole('button', { name: '请求返工', exact: true }).click()
      await select(summary)
    }
    await playtest.getByRole('button', { name: '载入这份报告的复现输入', exact: true }).click()
    await playtest.getByRole('button', { name: '执行这些路径', exact: true }).click()
    await expect(page.getByTestId('creative-playtest-report').getByRole('heading', { name: /指定路径通过/ })).toHaveCount(2)
    const milestone = page.getByTestId('creative-milestone')
    await milestone.getByRole('checkbox', { name: '模板起步 · 两位人物 fixture', exact: true }).check()
    await milestone.getByRole('checkbox', { name: '模板起步 · 修复悬空结局 fixture', exact: true }).check()
    await milestone.getByLabel('采用或撤销的原因').fill('采用两位人物与修复后经过实际双结局复测的章节')
    await milestone.getByRole('button', { name: '审阅采用', exact: true }).click()
    await expect(milestone.getByText('候选快照编译通过，请核对下面的文件变化。')).toBeVisible()
    await milestone.getByRole('button', { name: '确认写入项目', exact: true }).click()
    await expect(milestone.getByText(/最近一次采用已确认/)).toBeVisible()
    const adopted = await snapshot()
    expect(adopted.files['adv/chapters/01.adv.md']).toContain('让我再核对一次信上的名字。')
    expect(adopted.files['adv/chapters/01.adv.md']).not.toContain('missing#ending-leave')
    expect(adopted.files['adv/characters/lin.character.md']).toContain('先核对信封署名，再寻找收件人')
    await playtest.getByRole('combobox', { name: '执行快照', exact: true }).selectOption('saved')
    await playtest.getByRole('button', { name: '执行这些路径', exact: true }).click()
    await expect(page.getByTestId('creative-playtest-report').getByRole('heading', { name: /指定路径通过/ })).toHaveCount(2)
    await expect(playtest.getByText('已同步作者宿主报告，服务端未重放', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: '生成导演交付建议', exact: true }).click()
    await card('本地 fixture 导演交付建议').getByText('查看完整内容', { exact: true }).click()
    await expect(page.getByTestId('creative-director-summary')).toContainText('通过 2 · 失败 0')
    await select('本地 fixture 导演交付建议')
    const delivery = page.getByTestId('creative-delivery')
    await expect(delivery.getByLabel('采用、保留或排除的理由', { exact: true })).toHaveCount(7)
    for (const reason of await delivery.getByLabel('采用、保留或排除的理由', { exact: true }).all())
      await reason.fill('仅确认本地协议与保存成果；方案作参考，真实媒体和模型品质未验收。')
    await delivery.getByLabel('作者交付说明与剩余事项', { exact: true }).fill('结束模板起步的本地流程验证；图片和对白录音尚未制作，不代表六角色真实创作验收。')
    await delivery.getByRole('checkbox').check()
    await delivery.getByRole('button', { name: '审阅交付记录', exact: true }).click()
    await expect(delivery.getByText(/项目已编译/)).toBeVisible()
    await delivery.getByRole('button', { name: '确认记录并结束本次制作组', exact: true }).click()
    await expect(delivery.getByText(/作者已结束本次制作组/)).toBeVisible()
    const closed = await snapshot()
    expect(closed.files).toEqual(adopted.files)
    expect(closed.run.delivery.pendingMedia).not.toEqual([])
    for (const width of [1280, 390]) {
      await page.setViewportSize({ width, height: 900 })
      await delivery.scrollIntoViewIfNeeded()
      await page.screenshot({ path: info.outputPath(`template-adopted-${width}.png`), animations: 'disabled' })
    }
    await page.reload()
    await expect(delivery.getByText(/作者已结束本次制作组/)).toBeVisible()
    const reopened = await snapshot()
    expect(reopened.files).toEqual(adopted.files)
    expect(reopened.run.delivery).toEqual(closed.run.delivery)
    expect(reopened.calls.filter((call: string) => call.startsWith('POST'))).toEqual([])
    await writeFile(info.outputPath('template-start-journey.json'), JSON.stringify({ scope: 'Real product template writer, components, client, shared state machine/handoffs/validators, author edits, actual compiler and core paths, workspace adoption, grounded substitute director advice, independent author closure and IndexedDB reopen; model/service/identity/usage remain explicit local substitutes. No real six-role creativity, media, billing or quality certification.', initial, unapproved, candidates, repaired, adopted, closed, reopened }, null, 2))
  }
  finally {
    await writeFile(info.outputPath('browser-console.json'), JSON.stringify({ errors, warnings, state: await snapshot().catch(() => undefined) }, null, 2))
    expect(errors).toEqual([])
    expect(warnings).toEqual([])
  }
})
