import type { VoiceAuthoringSnapshot } from '@advjs/types'
import type { Page } from '@playwright/test'
import { expect, test } from '@playwright/test'

const lineId = 'line_019d137e-7abc-7000-8000-000000000001'
async function localSnapshot(page: Page): Promise<VoiceAuthoringSnapshot> {
  return page.evaluate(() => (window as unknown as { hostedAudioFixture: { snapshot: () => Promise<VoiceAuthoringSnapshot> } }).hostedAudioFixture.snapshot())
}
async function openJobs(page: Page) {
  await page.getByRole('button', { name: '生成配音', exact: true }).click()
  await expect(page.getByTestId('voice-jobs').locator('form').getByRole('button', { name: '审核生成计划' })).toBeEnabled()
}
async function enqueueAndRun(page: Page) {
  const jobs = page.getByTestId('voice-jobs')
  await jobs.getByRole('checkbox').check()
  await jobs.getByRole('button', { name: '审核生成计划' }).click()
  await expect(jobs.getByRole('button', { name: '确认并保存计划' })).toBeVisible()
  await jobs.getByRole('button', { name: '确认并保存计划' }).click()
  await expect(jobs.locator('[data-job-id]')).toHaveCount(1)
  await jobs.getByRole('button', { name: '执行已确认计划', exact: true }).click()
}
test.beforeEach(async ({ request }) => {
  await request.post('/fixture/reset')
})
test('syncs current Studio dialogue, imports the server identity, adopts it and publishes real Opus/AAC through COS HTTP', async ({ page, request }, testInfo) => {
  test.setTimeout(90000)
  const failures: string[] = []
  page.on('pageerror', error => failures.push(error.message))
  await page.goto('/')
  await expect(page.getByTestId('audio-workspace')).toBeVisible()
  await page.getByRole('textbox', { name: '测试作者对白' }).fill('作者刚修改的服务端配音。')
  await page.getByRole('button', { name: '保存对白', exact: true }).click()
  await openJobs(page)
  await enqueueAndRun(page)
  await expect.poll(async () => (await localSnapshot(page)).ledger.lines[lineId]?.locales['zh-CN']?.takes.length).toBe(1)
  const imported = (await localSnapshot(page)).ledger.lines[lineId]!.locales['zh-CN']!
  expect(imported.selectedTake).toBeNull()
  const server = await request.get('/fixture/status').then(response => response.json())
  expect(server.calls).toEqual([{ text: '作者刚修改的服务端配音。', character: 'hero' }])
  expect(imported.takes[0]).toEqual(server.snapshot.ledger.lines[lineId].locales['zh-CN'].takes[0])
  await page.screenshot({ path: testInfo.outputPath('studio-service-normal.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('studio-service-narrow.png'), fullPage: true })
  await page.getByRole('button', { name: '配音审核', exact: true }).click()
  await page.getByRole('button', { name: '绑定此 take', exact: true }).click()
  await expect.poll(async () => (await localSnapshot(page)).ledger.lines[lineId]!.locales['zh-CN']!.selectedTake).toBe(imported.takes[0]!.id)
  await page.evaluate(() => (window as any).hostedAudioFixture.sync())
  const selectedServer = await request.get('/fixture/status').then(response => response.json())
  expect(selectedServer.snapshot.ledger.lines[lineId].locales['zh-CN'].selectedTake).toBe(imported.takes[0]!.id)
  expect(selectedServer.calls).toHaveLength(1)
  await page.evaluate(() => (window as any).hostedAudioFixture.persist())
  await page.reload()
  await expect.poll(() => page.evaluate(() => Boolean((window as any).hostedAudioFixture))).toBe(true)
  await page.evaluate(() => (window as any).hostedAudioFixture.verify())
  await page.getByRole('button', { name: '配音审核', exact: true }).click()
  await expect(page.getByRole('button', { name: '清除正式选择', exact: true })).toBeVisible()
  const publication = page.getByTestId('audio-publication')
  await publication.getByRole('button', { name: '审核音频发布', exact: true }).click()
  await expect(publication.getByTestId('audio-publication-review')).toBeVisible({ timeout: 30000 })
  await publication.getByRole('button', { name: '发布已审核音频', exact: true }).click()
  await expect(publication.getByRole('link', { name: '查看公开音频目录', exact: true })).toBeVisible({ timeout: 30000 })
  const published = await request.get('/fixture/status').then(response => response.json())
  expect(published.calls).toHaveLength(1)
  expect(published.objects.map((object: { mimeType: string }) => object.mimeType.split(';')[0])).toEqual(expect.arrayContaining(['audio/webm', 'audio/mp4', 'application/json']))
  const manifestUrl = await publication.getByRole('link').getAttribute('href')
  const manifest = await request.get(manifestUrl!).then(response => response.json())
  expect(manifest.assets).toHaveLength(1)
  expect(manifest.assets[0].id).toBe(imported.takes[0]!.assetId)
  for (const privateField of ['voiceProfile', 'voice-ledger', 'spokenText', 'inputFingerprint', 'presetSha256', 'fixture-session'])
    expect(JSON.stringify(manifest)).not.toContain(privateField)
  const puts = published.requests.filter((request: { method: string }) => request.method === 'PUT')
  expect(puts.at(-1).key).toMatch(/\.json$/u)
  await page.screenshot({ path: testInfo.outputPath('studio-service-publication-narrow.png'), fullPage: true })
  await page.evaluate(() => (window as any).hostedAudioFixture.locale('en'))
  await expect(page.getByRole('heading', { name: 'Audio workspace', exact: true })).toBeVisible()
  await expect(page.getByRole('combobox', { name: 'Filter voice locale', exact: true })).toContainText('All locales')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('studio-service-en-narrow.png'), fullPage: true })
  expect(failures).toEqual([])
})
test('persists uncertain cancellation and restores it without dispatching a second supplier request', async ({ page, request }) => {
  await request.post('/fixture/hold')
  await page.goto('/')
  await openJobs(page)
  await enqueueAndRun(page)
  await expect.poll(async () => (await request.get('/fixture/status').then(response => response.json())).calls.length).toBe(1)
  const jobs = page.getByTestId('voice-jobs')
  await jobs.getByRole('button', { name: '取消任务', exact: true }).click()
  await expect(jobs.getByRole('button', { name: '恢复排队', exact: true })).toBeVisible()
  await jobs.getByRole('button', { name: '恢复排队', exact: true }).click()
  await expect(jobs.getByRole('button', { name: '执行已确认计划', exact: true })).toBeDisabled()
  await page.reload()
  await openJobs(page)
  await expect(jobs.locator('[data-job-id]')).toHaveCount(1)
  await expect(jobs.getByRole('button', { name: '执行已确认计划', exact: true })).toBeDisabled()
  expect((await request.get('/fixture/status').then(response => response.json())).calls).toHaveLength(1)
  expect((await localSnapshot(page)).ledger.lines[lineId]).toBeUndefined()
})
