  await replace(page, '# Original project private draft\n')
  await page.evaluate(() => (window as any).workspaceEditingFixture.holdWrite('README.md', false))
  await save(page).click()
  await expect.poll(() => page.evaluate(() => (window as any).workspaceEditingFixture.state().phase)).toBe('waiting')
