const errors = new WeakMap<Page, { errors: string[], warnings: string[], failedRequests: { url: string, error?: string }[] }>()
function observeErrors(page: Page) {
  const log = { errors: [] as string[], warnings: [] as string[], failedRequests: [] as { url: string, error?: string }[] }
  errors.set(page, log)
  page.on('pageerror', error => log.errors.push(error.message))
  page.on('requestfailed', request => log.failedRequests.push({ url: request.url(), error: request.failure()?.errorText }))
  page.on('console', (message) => {
    if (message.type() === 'error')
      log.errors.push(message.text())
    if (message.type() === 'warning')
      log.warnings.push(message.text())
  })
  return log
}
test.beforeEach(async ({ page }) => {
  observeErrors(page)
  await page.goto(`/tests/fixtures/creative-team/workspace-editing.html?id=${randomUUID()}`)
  await expect(page).toHaveTitle('Workspace file editing fixture')
  await page.waitForFunction(() => Boolean((window as any).workspaceEditingFixture))
  await expect(page.locator('vite-error-overlay')).toHaveCount(0)
  await page.locator('.workspace-segment ion-segment-button').filter({ hasText: '文件' }).click()
  await expect(page.locator('.workspace-text-preview:visible .monaco-editor')).toBeVisible()
})
test.afterEach(async ({ page }, info) => {
  await expect(page.locator('.workspace-file-operations')).toHaveAttribute('aria-busy', 'false')
  if (info.status !== info.expectedStatus) {
    await page.screenshot({ path: info.outputPath('before-cleanup.png') })
    await writeFile(info.outputPath('before-cleanup.md'), await page.locator('body').ariaSnapshot())
  }
  const cleanup = await page.evaluate(() => (window as any).workspaceEditingFixture.cleanup())
  await writeFile(info.outputPath('cleanup.json'), JSON.stringify(cleanup))
  await writeFile(info.outputPath('console.json'), JSON.stringify(errors.get(page)))
  expect(cleanup.removed).toBe(true)
  expect(errors.get(page)!.errors).toEqual([])
  expect(errors.get(page)!.warnings).toEqual([])
})
const editor = (page: Page) => page.locator('.workspace-text-preview:visible .monaco-editor')
const save = (page: Page) => page.locator('.workspace-text-preview:visible').getByRole('button', { name: '保存', exact: true })
const read = (page: Page, path = 'README.md') => page.evaluate(path => (window as any).workspaceEditingFixture.read(path), path)
async function replace(page: Page, text: string) {
  await editor(page).click()
  const mod = await page.evaluate(() => navigator.userAgent.includes('Macintosh')) ? 'Meta' : 'Control'
  await page.keyboard.press(`${mod}+a`)
  await page.keyboard.press('Backspace')
  await expect.poll(async () => (await editor(page).locator('.view-lines').textContent())?.trim()).toBe('')
  await page.keyboard.insertText(text)
  await expect(page.locator('.workspace-text-preview:visible')).toContainText('已修改')
}

