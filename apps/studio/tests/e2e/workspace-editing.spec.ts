test('the narrow native file browser cannot overwrite a real existing image as text', async ({ page }, info) => {
  const before = await page.evaluate(() => (window as any).workspaceEditingFixture.binary())
  await page.setViewportSize({ width: 390, height: 844 })
  await page.locator('.mobile-file-tree').getByRole('button', { name: 'assets', exact: true }).click()
  await page.locator('.mobile-file-tree').getByRole('button', { name: 'master.webp', exact: true }).click()
  await expect(page.locator('ion-modal.show-modal').getByRole('alert')).toContainText('只编辑 UTF-8 文本文件')
  await expect(editor(page)).toHaveCount(0)
  await expect(save(page)).toHaveCount(0)
  const after = await page.evaluate(() => (window as any).workspaceEditingFixture.binary())
  expect(before.bytes).toBe(202748)
  expect(before.sha256).toBe('aa2d012e89a6d7e0e8193f8c695317176fd7d39ecb0b1e30986dc358780af259')
  expect(after).toEqual(before)
  await page.screenshot({ path: info.outputPath('workspace-image-narrow.png') })
  await writeFile(info.outputPath('workspace-evidence.json'), JSON.stringify({ before, after }, null, 2))
})

