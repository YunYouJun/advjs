import type { RealQwenMetadata } from '../fixtures/real-qwen/journey'
import { cp, readFile, rm, writeFile } from 'node:fs/promises'
import { join, relative } from 'node:path'
import process from 'node:process'
import { expect, test } from '@playwright/test'
import { chooseOption, designVoice, files, generateAudition, generateDialogue, snapshot, verifyExport } from '../fixtures/real-qwen/journey'

test.skip(process.env.ADVJS_REAL_QWEN !== '1', 'Real model calls require explicit opt-in and the shared prepared root')
test('real Qwen design, original reference Base replacement, native Flow ZIP and production player', async ({ page, request }, info) => {
  const metadata: RealQwenMetadata = await request.get('/fixture/metadata').then(response => response.json())
  const pairingPath = join(metadata.directory, 'pairing.json')
  const pairing = JSON.parse(await readFile(pairingPath, 'utf8'))
  // The host keeps the capability in memory; discard the one-use private handoff
  // before any browser work, including failures during initial workspace load.
  await rm(pairingPath)
  const failures: string[] = []
  page.on('pageerror', error => failures.push(error.message))
  await page.goto('/')
  await expect(page.getByTestId('flow-workspace')).toBeVisible()
  await chooseOption(page, page.getByRole('combobox', { name: '章节', exact: true }), 'adv/chapters/intro.chapter.json', 'intro')
  await page.locator('.flow-node-list button').filter({ has: page.locator('code', { hasText: /^speech$/u }) }).click()
  const editor = page.getByTestId('flow-node-editor')
  await editor.getByLabel('文案', { exact: true }).fill(metadata.dialogueText)
  await editor.getByLabel('布局坐标 X', { exact: true }).fill('140')
  await editor.getByLabel('布局坐标 Y', { exact: true }).fill('240')
  await editor.getByLabel('布局坐标 Y', { exact: true }).blur()
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  await expect(editor.getByLabel('布局坐标 Y', { exact: true })).toHaveValue('0')
  await page.getByRole('button', { name: '重做', exact: true }).click()
  await page.locator('.flow-node-list button').filter({ has: page.locator('code', { hasText: /^route$/u }) }).click()
  const leftChoice = editor.locator('fieldset').filter({ has: page.locator('legend', { hasText: /^left$/u }) })
  await leftChoice.getByLabel('条件表达式（可选）', { exact: true }).fill('routeEnabled == true')
  await leftChoice.getByLabel('目标 / 跨章跳转', { exact: true }).fill('outcomes#left-end')
  await leftChoice.getByLabel('目标 / 跨章跳转', { exact: true }).blur()
  await page.getByRole('button', { name: '保存 JSON', exact: true }).click()
  await expect.poll(async () => JSON.parse((await files(page))['adv/chapters/intro.chapter.json']!).nodes[0].dialogues[0].text).toBe(metadata.dialogueText)
  const chapter = JSON.parse((await files(page))['adv/chapters/intro.chapter.json']!)
  expect(chapter.nodes[0]).toMatchObject({ position: { x: 140, y: 240 }, dialogues: [{ lineId: metadata.lineId, actorNote: 'retain-real-line-proof' }] })
  expect(chapter.notes).toEqual({ retained: 'real-qwen-layout-proof' })
  expect(chapter.nodes[1].choices[0]).toMatchObject({ id: 'left', when: 'routeEnabled == true', target: 'outcomes#left-end' })
  await page.getByRole('button', { name: '重载源文件', exact: true }).click()
  await expect.poll(async () => JSON.parse((await files(page))['adv/chapters/intro.chapter.json']!).nodes[0].dialogues[0].lineId).toBe(metadata.lineId)
  await page.screenshot({ path: info.outputPath('real-studio-flow-normal.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: info.outputPath('real-studio-flow-narrow.png'), fullPage: true })
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.getByRole('button', { name: '音频工作区', exact: true }).click()
  expect(await page.evaluate(() => (window as any).designFlowFixture.sessionState())).toEqual({ loggedIn: false, sdkProvided: false, localPaired: false })
  const connection = page.getByTestId('local-voice-connection')
  await connection.getByLabel('本地服务地址', { exact: true }).fill('http://127.0.0.1:3397')
  await connection.getByLabel('配对凭据', { exact: true }).fill(pairing.accessToken)
  await connection.getByRole('button', { name: '连接本地服务', exact: true }).click()
  await expect.poll(() => page.evaluate(() => (window as any).designFlowFixture.sessionState())).toEqual({ loggedIn: false, sdkProvided: false, localPaired: true })
  await expect(connection.getByLabel('配对凭据', { exact: true })).toHaveCount(0)
  expect(await page.evaluate(token => !JSON.stringify({ local: { ...localStorage }, session: { ...sessionStorage } }).includes(token), pairing.accessToken)).toBe(true)
  expect(JSON.stringify(await files(page)).includes(pairing.accessToken)).toBe(false)
  await page.screenshot({ path: info.outputPath('real-studio-local-pairing-normal.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: info.outputPath('real-studio-local-pairing-narrow.png'), fullPage: true })
  await page.setViewportSize({ width: 1280, height: 900 })
  await designVoice(page, metadata, 'designed')
  const designed = await generateAudition(page, info, metadata, 'design')
  const firstTake = await generateDialogue(page, metadata, 'design')
  const firstExport = await page.evaluate(() => (window as any).designFlowFixture.export())
  expect(firstExport.take).toMatchObject({ id: firstTake.id, assetId: firstTake.assetId, sha256: firstTake.sha256 })

  // The reference is the exact newly auditioned original synthesis, not a fake
  // waveform, a human recording or a claim that description seed is identity.
  await page.getByRole('button', { name: '资源库', exact: true }).click()
  await page.getByRole('button', { name: '导入音频', exact: true }).click()
  const form = page.locator('.audio-asset-form')
  await form.getByLabel('本地音频文件', { exact: true }).setInputFiles({ name: 'studio-original-qwen-reference.wav', mimeType: 'audio/wav', buffer: designed.wav })
  await chooseOption(page, form.getByRole('combobox', { name: '音频用途', exact: true }), 'reference', '参考音频')
  await form.getByLabel('名称', { exact: true }).locator('input').fill('Studio 本轮原创 Qwen 合成参考')
  await form.getByLabel('许可', { exact: true }).locator('input').fill('synthetic-acceptance-only')
  const priorIds = new Set((await snapshot(page)).catalog.assets.map(asset => asset.id))
  await form.getByRole('button', { name: '导入音频', exact: true }).click()
  await expect.poll(async () => (await snapshot(page)).catalog.assets.some(asset => !priorIds.has(asset.id) && asset.kind === 'reference')).toBe(true)
  const reference = (await snapshot(page)).catalog.assets.find(asset => !priorIds.has(asset.id) && asset.kind === 'reference')!
  expect(reference).toMatchObject({ sha256: designed.quality.sha256, bytes: designed.quality.bytes, license: 'synthetic-acceptance-only' })
  expect(reference).not.toHaveProperty('characterId')
  await page.evaluate(input => (window as any).realQwenFixture.recordReference(input), { assetId: reference.id, sampleAssetId: designed.sampleAssetId, sha256: designed.quality.sha256 })
  await designVoice(page, metadata, 'cloned', reference.id)
  const cloned = await generateAudition(page, info, metadata, 'base')
  expect(cloned.voice.design.locales['zh-CN'].providers[metadata.providerId].reference).toMatchObject({ assetId: reference.id, sha256: designed.quality.sha256, text: metadata.previewText, mode: 'icl' })
  const baseTake = await generateDialogue(page, metadata, 'base')
  const finalSnapshot = await snapshot(page)
  expect(finalSnapshot.ledger.lines[metadata.lineId]!.locales['zh-CN']!.takes.map(take => take.id)).toEqual([firstTake.id, baseTake.id])
  const secondExport = await page.evaluate(() => (window as any).designFlowFixture.export())
  expect(secondExport.take).toMatchObject({ id: baseTake.id, assetId: baseTake.assetId, sha256: baseTake.sha256 })
  if (metadata.publicationEnabled) {
    const panel = page.getByTestId('audio-publication')
    await panel.getByRole('button', { name: '审核音频发布', exact: true }).click()
    await expect(panel.getByTestId('audio-publication-review')).toBeVisible({ timeout: 180_000 })
    await expect(panel.getByTestId('audio-publication-review')).toContainText('1 项音频，2 个播放文件')
    await panel.getByRole('button', { name: '发布已审核音频', exact: true }).click()
    const manifestLink = panel.getByRole('link', { name: '查看公开音频目录', exact: true })
    await expect(manifestLink).toBeVisible({ timeout: 180_000 })
    const manifestUrl = (await manifestLink.getAttribute('href'))!
    expect(manifestUrl).toMatch(/^https:\/\/[^/]+\.cos\.ap-shanghai\.myqcloud\.com\/games\/advjs-audio-acceptance-20261012\/v1\/manifests\/assets\.[a-f0-9]{64}\.json$/u)
    const revision = manifestUrl.match(/assets\.([a-f0-9]{64})\.json$/u)![1]
    const nativeRoot = join(metadata.directory, 'published-native')
    await cp(secondExport.root, nativeRoot, { recursive: true, filter: path => !relative(secondExport.root, path).split(/[\\/]/u).some(part => ['node_modules', 'dist', '.advjs'].includes(part)) })
    await writeFile(join(metadata.directory, 'publication.json'), JSON.stringify({ project: nativeRoot, publication: { manifestUrl, revision } }, null, 2))
    await writeFile(info.outputPath('local-qwen-cos-publication-proof.json'), JSON.stringify({ mode: 'local-pairing-real-qwen-real-cos', loggedIn: false, cloudTts: false, cfs: false, lineId: metadata.lineId, take: baseTake, publication: { manifestUrl, revision } }, null, 2))
    await page.screenshot({ path: info.outputPath('real-studio-cos-publication.png'), fullPage: true })
  }
  const rights = JSON.parse((await files(page))[metadata.rightsPath]!)
  expect(rights).toMatchObject({ source: 'synthetic-qwen-voice-design', humanVoice: false, humanConsentClaimed: false, reference: { assetId: reference.id, originalSampleAssetId: designed.sampleAssetId, sha256: designed.quality.sha256 } })
  const status = await request.get('/fixture/status').then(response => response.json())
  expect(status.calls).toHaveLength(4)
  expect(status.calls.every((call: any) => call.offline === true)).toBe(true)
  expect(status.calls.map((call: any) => call.manifest.generationMode)).toEqual(['voice-design', 'voice-design', 'reference-icl', 'reference-icl'])
  expect(status.calls.every((call: any) => call.quality.nativeSampleRate === 24000 && call.quality.rms > 1e-4 && call.quality.peak > 1e-4)).toBe(true)
  expect(status.calls[0].candidates[0]).toMatchObject({ model: metadata.models.design.model, revision: metadata.models.design.revision })
  expect(status.calls[2].candidates[0]).toMatchObject({ model: metadata.models.base.model, revision: metadata.models.base.revision })
  expect(status.snapshot.ledger.lines[metadata.lineId].locales['zh-CN'].selectedTake).toBe(baseTake.id)
  expect(failures).toEqual([])
  await writeFile(info.outputPath('real-qwen-native-proof.json'), JSON.stringify({ schemaVersion: 1, metadata, auditions: { designed: designed.quality, base: cloned.quality }, reference: { asset: reference, origin: { originalSampleAssetId: designed.sampleAssetId, source: 'synthetic-qwen-voice-design', humanVoice: false }, rights }, selectedSamples: { design: designed.sampleAssetId, base: cloned.sampleAssetId }, calls: status.calls, takes: [firstTake, baseTake], exports: [firstExport, secondExport] }, null, 2))
  await verifyExport(page, info, metadata, 'design', firstExport, status.calls[1].candidates[0])
  await verifyExport(page, info, metadata, 'base', secondExport, status.calls[3].candidates[0])
  expect((await request.get('/fixture/status').then(response => response.json())).calls).toHaveLength(4)
})
