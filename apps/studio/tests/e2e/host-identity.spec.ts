import { writeFile } from 'node:fs/promises'
import { expect, test } from '@playwright/test'

const records = new Map<string, { errors: string[], warnings: string[], posts: string[] }>()
test.beforeEach(async ({ page }, info) => {
  const record = { errors: [] as string[], warnings: [] as string[], posts: [] as string[] }
  records.set(info.testId, record)
  page.on('pageerror', error => record.errors.push(error.message))
  page.on('console', (message) => {
    if (message.type() === 'error')
      record.errors.push(message.text())
    if (message.type() === 'warning')
      record.warnings.push(message.text())
  })
  await page.route('**/fixture-service/**', async (route) => {
    const request = route.request()
    if (request.method() === 'POST')
      record.posts.push(request.headers().authorization ?? '')
    await route.fulfill({ json: request.url().endsWith('/points/me') ? { availableMicroPoints: request.headers().authorization?.includes('next-author') ? 222000 : 123000, reservedMicroPoints: 0, chargedMicroPoints: 0 } : {} })
  })
  await page.goto('/tests/fixtures/creative-team/managed-session.html?coordinator=1')
  await expect(page.getByTestId('actor')).toHaveText('author')
  await expect(page.locator('.agent-console__points dd').first()).toHaveText('123')
})
test.afterEach(async ({ page }, info) => {
  const record = records.get(info.testId)!
  await page.screenshot({ path: info.outputPath('final.png'), fullPage: true })
  await writeFile(info.outputPath('browser-console.json'), `${JSON.stringify(record, null, 2)}\n`)
  records.delete(info.testId)
  expect(record.errors).toEqual([])
  expect(record.warnings).toEqual([])
})

test('ignores an old host response and shows the latest account balance', async ({ page }) => {
  await page.getByRole('button', { name: 'Hold host response', exact: true }).click()
  await page.getByRole('button', { name: 'Host author', exact: true }).click()
  await expect(page.getByTestId('host')).toHaveText('held')
  await page.getByRole('button', { name: 'Host next account', exact: true }).click()
  await expect(page.getByTestId('actor')).toHaveText('signed out')
  await page.getByRole('button', { name: 'Release host response', exact: true }).click()
  await expect(page.getByTestId('actor')).toHaveText('next-author')
  await expect(page.locator('.agent-console__points dd').first()).toHaveText('222')
  await expect(page.getByTestId('identity-calls')).toHaveText('signout,signout,signin:next-author')
})
test('waits for the old SDK write before the new host identity can write', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Hold SDK write', exact: true }).click()
  await page.getByRole('button', { name: 'Host author', exact: true }).click()
  await expect(page.getByTestId('write')).toHaveText('held')
  await page.getByRole('button', { name: 'Host next account', exact: true }).click()
  await expect(page.getByTestId('actor')).toHaveText('signed out')
  await expect(page.getByTestId('identity-calls')).toHaveText('signout,signin:author')
  await page.getByRole('button', { name: 'Release SDK write', exact: true }).click()
  await expect(page.getByTestId('actor')).toHaveText('next-author')
  await expect(page.locator('.agent-console__points dd').first()).toHaveText('222')
  await expect(page.getByTestId('identity-calls')).toHaveText('signout,signin:author,signout,signin:next-author')
})
test('lets explicit logout supersede a pending host authorization', async ({ page }) => {
  await page.getByRole('button', { name: 'Hold host response', exact: true }).click()
  await page.getByRole('button', { name: 'Host author', exact: true }).click()
  await expect(page.getByTestId('host')).toHaveText('held')
  await page.getByRole('button', { name: 'Coordinator logout', exact: true }).click()
  await page.getByRole('button', { name: 'Release host response', exact: true }).click()
  await expect(page.getByTestId('outcome')).toHaveText('complete')
  await expect(page.getByTestId('actor')).toHaveText('signed out')
  await expect(page.getByTestId('identity-calls')).toHaveText('signout,signout')
})
test('does not submit an old AI request after its queued SDK token read returns', async ({ page }, info) => {
  await page.getByRole('button', { name: 'Hold next token', exact: true }).click()
  await page.getByRole('button', { name: 'Submit AI', exact: true }).click()
  await expect(page.getByTestId('token')).toHaveText('held')
  await page.getByRole('button', { name: 'Host next account', exact: true }).click()
  await expect(page.getByTestId('actor')).toHaveText('signed out')
  await page.getByRole('button', { name: 'Release old token', exact: true }).click()
  await expect(page.getByTestId('outcome')).toHaveText('blocked')
  await expect(page.getByTestId('actor')).toHaveText('next-author')
  await expect(page.locator('.agent-console__points dd').first()).toHaveText('222')
  expect(records.get(info.testId)!.posts).toEqual([])
})
