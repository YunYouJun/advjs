/** Existing product controls configure author-owned media metadata before the model substitute runs. */
export async function configureTemplateRecording(page: Page, returnUrl: string, bridge = 'creativeAuthorFixture') {
  await page.goto('/tabs/workspace/characters')
  await page.getByRole('button', { name: '创建角色', exact: true }).click()
  const form = page.locator('.cef')
  await form.getByRole('textbox', { name: '角色 ID', exact: true }).fill('lin')
  await form.getByRole('textbox', { name: '角色名', exact: true }).fill('林舟')
  const voice = form.locator('.voice-profile-fields')
  await voice.locator('[data-field="locale"] input').fill('zh-CN')
  await voice.locator('[data-field="providerId"] input').fill('local-system')
  await voice.locator('[data-field="model"] input').fill('macos-say')
  await voice.locator('[data-field="voiceId"] input').fill('Tingting')
  await voice.getByRole('combobox').last().click()
  await page.getByRole('option', { name: '系统声音', exact: true }).click()
  await voice.getByRole('button', { name: '应用服务绑定', exact: true }).click()
  await expect(voice).toContainText('zh-CN · local-system')
  await page.locator('.cem-save-btn:visible').click()
  await expect(page.locator('.cem-save-btn:visible')).toHaveCount(0)
  await page.goto('/tabs/workspace/audio')
  await page.getByRole('button', { name: '创建原生目录', exact: true }).click()
  await expect(page.getByRole('button', { name: '创建原生目录', exact: true })).toHaveCount(0)
  await page.goto(returnUrl)
  await expect.poll(() => page.evaluate(bridge => Boolean((window as any)[bridge]), bridge)).toBe(true)
}

